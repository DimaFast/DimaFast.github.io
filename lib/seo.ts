export const pageSlugs = [
  ...Object.keys(overview),
  ...serviceSlugs,
  ...Object.keys(details),
  ...Object.keys(doctorProfiles),
]
export const isIndexable = process.env.SITE_INDEXABLE === 'true'

export function pageMetadata(slug = ''): Metadata {
  const page = overview[slug as keyof typeof overview] ?? detailSeo[slug]
  const title = page ? `${page[0]} | Вербена` : 'Медичний центр «Вербена» у Хмельницькому'
  const description = page?.[1] ?? site.description
  const path = slug ? `/${slug}/` : '/'
  const image =
    doctorProfiles[slug]?.image ??
    details[slug]?.image ??
    getServicePage(slug)?.photo ??
    '/share-logo.png'

  return {
    title,
    description,
    alternates: { canonical: path },
    robots: isIndexable
      ? { index: true, follow: true, 'max-image-preview': 'large' }
      : { index: false, follow: false },
    openGraph: {
      title,
      description,
      url: new URL(path, site.url),
      locale: 'uk_UA',
      type:
        details[slug]?.kind === 'editorial' || details[slug]?.kind === 'article'
          ? 'article'
          : 'website',
      siteName: site.name,
      images: [{ url: image, alt: site.name }],
    },
    twitter: { card: 'summary_large_image', title, description, images: [image] },
  }
}
